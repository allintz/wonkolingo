export async function tidyChecks(p) {
  return p.evaluate(async () => {
    const results=[], check=(v,n)=>results.push([!!v,n]);
    state=normalizeState({}); state.mix={}; state.keyTerms={}; SKIPPED.clear();
    check(!COURSES.tools2 && COURSES.tools && COURSES.basics, 'Toolkit replaces v2; Basics exists');
    check(courseCards('basics').length===11, 'Basics has eleven cards');
    const migrated=normalizeState({course:'tools2',mix:{tools2:{on:true,perDay:3}},srs:{'vu0l0#nrrd1tc':{last:'2026-10-20',due:'2026-10-21',s:2,at:1}}});
    check(migrated.course==='tools'&&migrated.mix.tools.on&&!migrated.mix.tools2, 'old course selection and mix migrate');
    state=migrated;
    check(srsOf('tu0l0#nrrd1tc')?.at===1, 'v2 history carries to original Toolkit id');
    check(!newCardsAvailable('tools').some(c=>equivalentIds(c.id).includes('tu0l0#nrrd1tc')), 'v2 learned card never treated as new');
    check(courseKeyForCard('vu1l0#nbd8nwu')==='tools', 'moved v-prefix card belongs to Toolkit');
    // Three equivalent cards across courses, with a deliberately mutual edge.
    const item=(id,dup)=>({id,t:'mc',p:'Test mechanism?',o:['A','B','C','D'],a:0,x:'Test',dup});
    COURSES.qa={name:'QA',caveat:[],meta:'test',pre:'q',units:[{title:'Q',lessons:[{title:'Q',items:[item('qu0l0#one',['wu0l0#two','xu0l0#three'])]}]}]};
    COURSES.qb={name:'QB',caveat:[],meta:'test',pre:'w',units:[{title:'Q',lessons:[{title:'Q',items:[item('wu0l0#two','xu0l0#three')]}]}]};
    COURSES.qc={name:'QC',caveat:[],meta:'test',pre:'x',units:[{title:'Q',lessons:[{title:'Q',items:[item('xu0l0#three','qu0l0#one')]}]}]};
    state=normalizeState({mix:{qa:{on:true},qb:{on:true},qc:{on:true}}}); SKIPPED.clear();
    check(['qa','qb','qc'].flatMap(newCardsAvailable).length===1,'multi-target, reverse and mutual links yield exactly one card');
    state.srs['wu0l0#two']={s:2,d:3,last:'2026-10-20',due:'2026-10-21',at:10};
    check(['qa','qb','qc'].flatMap(newCardsAvailable).length===0,'learning any copy suppresses new equivalents');
    check(dueCards('2026-10-23').filter(c=>c.course.startsWith('q')).length===1,'equivalent reviews scheduled once');
    state.mix.qb.on=false;
    check(dueCards('2026-10-23').filter(c=>c.course.startsWith('q')).length===1,'review history transfers when original course switched off');
    state.removed={'wu0l0#two':{at:20,reason:'none'}};
    check(isRemoved('qu0l0#one')&&dueCards('2026-10-23').length===0,'removal shared across inactive courses');
    state.removed['qu0l0#one']={at:30,off:true};
    check(!isRemoved('xu0l0#three'),'newest restore restores entire group');
    SKIPPED.add('wu0l0#two');
    check(dueCards('2026-10-23').length===0,'Skip for now shared across copies');
    SKIPPED.clear(); state.srs={};
    state.keyTerms={'copy:wu0l0#two':{at:50,known:[],home:'wu0l0#two'}};
    check(['qa','qc'].flatMap(newCardsAvailable).length===0,'skip remembers original copy across reload while original course off');
    state.mix.qb.on=true;
    check(newCardsAvailable('qb').length===1,'original skipped copy returns later in its own course');
    state.keyTerms={}; state.mix={qa:{on:true},qb:{on:true},qc:{on:true}};
    refreshDone(); check(Object.values(state.done).some(Boolean),'hidden duplicate lessons get completion checkmarks');
    state.srs={};state.removed={};state.mix={policy:{on:true},tools:{on:true}};state.keyTerms={};
    check(basicsChecklist('policy').length===11,'course shows relevant unlearned basics');
    go('course','policy');openBasics('policy');
    check(document.querySelectorAll('#ktSheet [data-kt]').length===11,'Basics checklist renders one toggle per card');
    document.querySelector('#ktSheet input[data-kt]').click(); check(document.querySelector('#ktSheet input[data-kt]').checked,'familiar checkbox records an individual selection');
    document.querySelector('#ktAll').click();
    check(basicsChecklist('tools').length===0,'familiar basics omitted across courses');
    check(!newCardsAvailable('tools').some(c=>c.lessonId==='tbasics'),'familiar basics omitted from sessions');
    state.keyTerms={};state.srs={'hu0l0#ni67fn0':{s:2,last:'2026-10-20',due:'2026-10-30',at:5}};
    check(basicsChecklist('policy').length===10,'existing course knowledge carries backward into Basics');
    state.keyTerms={policy:{at:10,known:['open-weight']}};state.srs={};
    const other=courseCards('powers').find(c=>c.item._gterm==='open-weight');
    check(isFamiliar(other.id),'known glossary terms shared across courses');
    const termA=courseCards('policy').find(c=>c.item._gterm==='open-weight');
    state.keyTerms={};state.removed={[termA.id]:{at:10}};
    check(isRemoved(other.id),'removed glossary terms shared across courses');
    state.removed={};state.keyTerms={};state.mix={qa:{on:true},qb:{on:true},qc:{on:true}};state.srs={'wu0l0#two':{s:2,last:'2026-10-20',due:'2026-10-30',at:5}};
    go('course','qa');startLesson(0);
    check(!run,'direct lesson cannot serve hidden duplicate');
    delete COURSES.qa;delete COURSES.qb;delete COURSES.qc; sharedCache=null;
    state=normalizeState({});state.mix={};go('courses');
    check(/Start here/.test(document.querySelector('#coursesBody').textContent),'course shelves include Start here');
    return results;
  });
}
