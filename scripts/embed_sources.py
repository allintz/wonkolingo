#!/usr/bin/env python3
"""Embed per-card source links into the page source, for the small "Source:" links under explanations.
Usage: python3 scripts/embed_sources.py [<vault WonkoLingo folder>]
Reads every courses/*.sources.json (lists of {id, src: [urls]}) and replaces the CARD-SOURCES block in wonkolingo.html."""
import glob, json, os, re, sys

folder = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Documents/Obsidian Vault/05_Reference/WonkoLingo')
page = os.path.join(folder, 'wonkolingo.html')
out = {}
for f in sorted(glob.glob(os.path.join(folder, 'courses', '*.sources.json'))):
    for c in json.load(open(f)):
        urls = [u for u in (c.get('src') or []) if isinstance(u, str) and re.match(r'^https?://', u)]
        if c.get('id') and urls:
            out[c['id']] = list(dict.fromkeys(urls))[:3]
block = '/* CARD-SOURCES START (generated by scripts/embed_sources.py from courses/*.sources.json) */\nconst CARD_SOURCES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + ';\n/* CARD-SOURCES END */\n'
s = open(page).read()
m = re.search(r'/\* CARD-SOURCES START.*?/\* CARD-SOURCES END \*/\n', s, flags=re.S)
if m:
    s = s[:m.start()] + block + s[m.end():]
else:
    i = s.find('const COURSES = ')
    if i < 0: sys.exit('COURSES not found')
    s = s[:i] + block + s[i:]
open(page, 'w').write(s)
print(f'embedded sources for {len(out)} cards')
